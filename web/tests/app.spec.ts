import {test,expect} from '@playwright/test'
import path from 'node:path'

test.use({launchOptions:{args:['--enable-features=WebMachineLearningNeuralNetwork']}})
test.beforeEach(async ({page,request}) => {
 const health=await (await request.get('/api/health')).json()
 const model=health.webnn_models.find(candidate=>candidate.model==='qwen2.5-1.5b:webnn')
 test.skip(!model,'Qwen2.5 1,5B doit être installé dans Clair.')
 await page.addInitScript(modelId=>localStorage.setItem('clair-webnn-model',modelId),model.model)
})

test('PDF, réponse WebNN, sources, persistance et écran mobile',async({page}, testInfo)=>{
 const external:string[]=[],errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/*',route=>{const url=new URL(route.request().url());if(!['127.0.0.1','localhost'].includes(url.hostname)){external.push(url.href);return route.abort()}return route.continue()})
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Faites parler vos documents.'})).toBeVisible()
 await page.screenshot({path:testInfo.outputPath('accueil.png'),fullPage:true})
 await page.locator('input[type=file]').setInputFiles(path.resolve('../tests/fixtures/horizon.pdf'))
 await expect(page.getByRole('heading',{name:'horizon',exact:true})).toBeVisible()
 await expect(page.getByText('WebNN disponible')).toBeVisible()
 await page.getByLabel('Format de réponse').selectOption('réponse courte')
 await page.getByLabel('Votre question').fill('Quel est le budget annoncé pour 2027 ?')
 await page.getByRole('button',{name:'Envoyer la question'}).click()
 await expect(page.locator('.messages .exchange').last().locator('.answer')).toContainText('240 000',{timeout:90000})
 await expect(page.locator('.stream-status')).toHaveCount(0,{timeout:90000})
 const answer=page.locator('.messages .exchange').last().locator('.answer')
 await expect(answer).toContainText('WebNN')
 await answer.getByRole('button',{name:/Page 2/}).click()
 await expect(page.locator('.source-panel')).toContainText('240 000')
 await expect(page.locator('.source-panel').getByRole('heading',{name:'Page 2',exact:true})).toBeVisible()
 await page.screenshot({path:testInfo.outputPath('sources.png'),fullPage:true})
 await page.getByRole('button',{name:'Fermer la source'}).click()
 await page.reload()
 await page.locator('.doc-item').filter({hasText:'horizon.pdf'}).first().click()
 await expect(page.locator('.messages')).toContainText('240 000')
 await page.getByRole('button',{name:'Paramètres du modèle'}).click()
 await expect(page.locator('.settings')).toBeVisible()
 await page.setViewportSize({width:390,height:844})
 await expect(page.getByLabel('Votre question')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
 await page.screenshot({path:testInfo.outputPath('mobile.png'),fullPage:true})
 expect(external).toEqual([])
 expect(errors).toEqual([])
})

test('DOCX, démonstration et question absente sans référence inventée',async({page})=>{
 await page.goto('/')
 await page.locator('input[type=file]').setInputFiles(path.resolve('../tests/fixtures/horizon.docx'))
 await expect(page.getByRole('heading',{name:'horizon',exact:true})).toBeVisible()
 await expect(page.locator('.document-warnings')).toContainText('Pagination physique indisponible')
 await page.locator('.outline button').first().click()
 await expect(page.locator('.source-panel').getByRole('heading',{name:'Bloc 1',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Fermer la source'}).click()
 await page.goto('/')
 await page.getByRole('button',{name:/Ouvrir le document de démonstration/}).click()
 await expect(page.getByRole('heading',{name:'Démonstration — Projet Horizon'})).toBeVisible()
 await page.getByLabel('Votre question').fill('Quel est le budget pour 2099 ?')
 await page.getByRole('button',{name:'Envoyer la question'}).click()
 await expect(page.locator('.messages .exchange').last().locator('.answer')).toContainText('Information introuvable')
 await expect(page.locator('.messages .exchange').last().locator('.answer')).toContainText('WebNN')
})
